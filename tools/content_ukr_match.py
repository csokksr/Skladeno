def m(topic, prompt, pairs, extra, explanation, level=2):
    """pairs: [(left, right)] — 4 rows; extra: the option that matches nothing."""
    qid = f'ukr-match-20261021-{len(Q) + 1:02d}'
    right = [r for _, r in pairs] + [extra]
    assert len(pairs) == 4 and len(set(right)) == 5
    random.Random(qid).shuffle(right)
    Q.append({'id': qid, 'subject': 'ukr', 'topicId': topic, 'type': 'match', 'prompt': prompt,
              'left': [l for l, _ in pairs], 'right': right, 'options': right, 'answer': [right.index(r) for _, r in pairs],
              'explanation': explanation, 'level': level, 'tags': ['match', topic.split('-', 1)[1]]})


